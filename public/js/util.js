const AVATAR_PALETTE = [
  '#594a3e',
  '#4a5448',
  '#3d4e56',
  '#524357',
  '#614539',
  '#4f5b5b',
  '#5a533c',
  '#454c59'
];

export function getAvatarColor(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % AVATAR_PALETTE.length;
  return AVATAR_PALETTE[index];
}

export function createAvatarElement(member) {
  const div = document.createElement('div');
  div.className = 'avatar' + (member.buffering ? ' is-buffering' : '') + (!member.connected ? ' is-offline' : '');
  div.style.backgroundColor = getAvatarColor(member.name || member.clientId || 'G');
  div.title = member.name + (member.isHost ? ' (Host)' : '');

  const letter = document.createElement('span');
  letter.className = 'avatar-letter';
  letter.textContent = (member.name || 'G')[0].toUpperCase();
  div.appendChild(letter);

  if (member.isHost) {
    const crownWrap = document.createElement('span');
    crownWrap.className = 'avatar-crown';
    crownWrap.innerHTML = ICONS.crown;
    div.appendChild(crownWrap);
  }

  return div;
}

export function formatTime(seconds) {
  if (isNaN(seconds) || seconds < 0) return '00:00';
  const sec = Math.floor(seconds);
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;
  const pad = (n) => String(n).padStart(2, '0');
  if (h > 0) {
    return `${h}:${pad(m)}:${pad(s)}`;
  }
  return `${pad(m)}:${pad(s)}`;
}

export function showToast(message, type = 'info') {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.textContent = message;
  container.appendChild(toast);

  setTimeout(() => {
    toast.classList.add('is-hidden');
    setTimeout(() => toast.remove(), 200);
  }, 3200);
}

export function getStoredClientId() {
  let id = localStorage.getItem('couchlight_client_id');
  if (!id) {
    id = 'c_' + Math.random().toString(36).slice(2, 10);
    localStorage.setItem('couchlight_client_id', id);
  }
  return id;
}

export function getStoredNickname() {
  return localStorage.getItem('couchlight_nickname') || '';
}

export function setStoredNickname(name) {
  if (name) {
    localStorage.setItem('couchlight_nickname', name.trim().slice(0, 20));
  }
}
